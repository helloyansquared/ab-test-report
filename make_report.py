"""Build report/report.html from report/results.json and the charts."""
import base64
import json
from pathlib import Path

R = json.loads(Path("report/results.json").read_text())
img = lambda f: "data:image/png;base64," + base64.b64encode(Path("report", f).read_bytes()).decode()
pct = lambda v, d=1: f"{v*100:.{d}f}%"
spct = lambda v, d=0: f"{v*100:+.{d}f}%"
c, rpv, aov, nov, pw = R["conversion"], R["revenue_per_visitor"], R["aov"], R["novelty"], R["power"]
seg = {r["segment"]: r for r in R["segments"]}
mob, desk = seg["device: mobile"], seg["device: desktop"]
peak = max(R["cumulative"], key=lambda r: r["rel_lift"])
peak_day = R["cumulative"].index(peak) + 1

seg_rows = "".join(
    f"<tr><td>{r['segment'].split(': ')[1].capitalize()}</td><td>{r['n']:,}</td>"
    f"<td>{pct(r['cr_A'],2)}</td><td>{pct(r['cr_B'],2)}</td>"
    f"<td>{spct(r['rel_lift'])} <span class=m>({spct(r['rel_ci'][0])} to {spct(r['rel_ci'][1])})</span></td>"
    f"<td>{r['p_holm']:.3f}</td></tr>"
    for r in R["segments"]
)

html = f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>A/B test report: one-page checkout</title>
<style>
body{{font-family:Inter,Segoe UI,Helvetica,Arial,sans-serif;color:#1f2a37;max-width:820px;margin:40px auto;padding:0 22px;line-height:1.55}}
h1{{font-size:28px;margin:0 0 4px}} h2{{font-size:19px;margin:34px 0 10px;border-top:1px solid #e5e7eb;padding-top:22px}}
.sub{{color:#6b7280;margin:0 0 22px}} .note{{background:#fff7e6;border:1px solid #f5d38a;padding:8px 12px;border-radius:8px;font-size:13px;color:#7a5200}}
.verdict{{background:#ecfdf5;border:1px solid #a7f3d0;border-radius:12px;padding:16px 20px;margin:18px 0}}
.verdict b{{color:#0f766e}} .kpis{{display:grid;grid-template-columns:repeat(3,1fr);gap:12px;margin:16px 0}}
.kpi{{border:1px solid #e5e7eb;border-radius:12px;padding:12px 14px}} .kpi .v{{font-size:24px;font-weight:700;color:#0f766e}}
.kpi .l{{font-size:13px;color:#6b7280}} .kpi.grey .v{{color:#6b7280}}
table{{border-collapse:collapse;width:100%;font-size:14px}} td,th{{border-bottom:1px solid #eef0f2;padding:7px 8px;text-align:left}}
th{{color:#6b7280;font-weight:600}} .m{{color:#6b7280;font-size:12px}} img{{max-width:100%}}
li{{margin:4px 0}}
</style></head><body>
<p class="note">Portfolio demo. The shop and every number come from a <b>fictional dataset</b> generated by <code>make_data.py</code>. The analysis itself is real and reproducible.</p>
<h1>Does the one-page checkout sell more?</h1>
<p class="sub">Northwind Outfitters (fictional) &middot; A = current 3-step checkout, B = new one-page checkout &middot; 14 days &middot; {R['srm']['n_A']+R['srm']['n_B']:,} visitors</p>

<div class="verdict"><b>Recommendation: ship B.</b> It lifts conversion by about {spct(c['rel_lift'])} ({spct(c['rel_ci'][0])} to {spct(c['rel_ci'][1])}, p = {c['p']:.3f}). Plan for a long-run lift closer to {spct(nov['days_4_14']['rel_lift'])}: the first days were inflated by a novelty effect. Keep watching order value, which may dip slightly.</div>

<div class="kpis">
<div class="kpi"><div class="v">{spct(c['rel_lift'])}</div><div class="l">conversion rate<br>{pct(c['cr_A'],2)} &rarr; {pct(c['cr_B'],2)}</div></div>
<div class="kpi"><div class="v">{spct(rpv['rel_lift'])}</div><div class="l">revenue per visitor<br>&euro;{rpv['A']:.2f} &rarr; &euro;{rpv['B']:.2f} (borderline)</div></div>
<div class="kpi grey"><div class="v">{"&minus;" if aov['diff']<0 else "+"}&euro;{abs(aov['diff']):.2f}</div><div class="l">average order value<br>not conclusive</div></div>
</div>

<h2>1. Is the test itself trustworthy?</h2>
<ul>
<li><b>Traffic split:</b> {R['srm']['n_A']:,} vs {R['srm']['n_B']:,} visitors. A sample-ratio check against 50/50 gives p = {R['srm']['p']:.2f}, so no sign of a broken randomiser.</li>
<li><b>Sensitivity:</b> with this sample, the test could reliably detect (80% power) a lift of about {spct(pw['mde_rel'])} or more. The observed lift is right at that size, so the result is real but the exact number is uncertain.</li>
</ul>

<h2>2. Conversion</h2>
<img src="{img('conversion.png')}" alt="Conversion rate by variant">
<p>B converts {pct(c['cr_B'],2)} of visitors vs {pct(c['cr_A'],2)} for A: {c['abs_diff']*100:+.2f} percentage points (95% CI {c['abs_ci'][0]*100:+.2f} to {c['abs_ci'][1]*100:+.2f}). Two-proportion z-test p = {c['p']:.3f}.</p>

<h2>3. Money, not just clicks</h2>
<ul>
<li><b>Revenue per visitor:</b> &euro;{rpv['A']:.2f} &rarr; &euro;{rpv['B']:.2f}. Bootstrap 95% CI for the difference &euro;{rpv['ci'][0]:+.2f} to &euro;{rpv['ci'][1]:+.2f}; Welch t-test p = {rpv['p']:.3f}. Likely positive, but not as solid as the conversion result.</li>
<li><b>Average order value:</b> &euro;{aov['A']:.2f} &rarr; &euro;{aov['B']:.2f} (CI &euro;{aov['ci'][0]:+.2f} to &euro;{aov['ci'][1]:+.2f}). Buyers in B may spend a little less per order, a plausible side effect of showing fewer add-ons. Worth monitoring after launch.</li>
</ul>

<h2>4. Who benefits?</h2>
<img src="{img('segments.png')}" alt="Lift by segment">
<table><tr><th>Segment</th><th>Visitors</th><th>A</th><th>B</th><th>Lift (95% CI)</th><th>p (Holm)</th></tr>{seg_rows}</table>
<p>The gain is clearest on <b>mobile</b> ({spct(mob['rel_lift'])}, Holm-adjusted p = {mob['p_holm']:.3f}). On desktop the lift is {spct(desk['rel_lift'])} and not significant. A formal interaction test (logistic regression) gives p = {R['interaction_p_device']:.2f}, so we <b>cannot</b> claim the effect truly differs by device. Segment results are corrected for multiple comparisons (Holm).</p>

<h2>5. Watch out for early results</h2>
<img src="{img('cumulative.png')}" alt="Cumulative lift by day">
<p>On day {peak_day} the cumulative lift read {spct(peak['rel_lift'])} with p = {peak['p']:.3f}. Stopping there would have overstated the gain about threefold. Days 1&ndash;3 show {spct(nov['days_1_3']['rel_lift'])}; days 4&ndash;14 show {spct(nov['days_4_14']['rel_lift'])}. That pattern fits a novelty effect, so the steady-state estimate is the safer number for forecasting.</p>

<h2>Methods</h2>
<p class="m">Sample-ratio chi-square test; two-proportion z-test with Newcombe CI; bootstrap (4,000 resamples) and Welch t-test for revenue per visitor; bootstrap CI and Mann-Whitney U for order value; per-segment z-tests with Holm correction; logistic regression <code>converted ~ variant * device + visitor_type</code> for the interaction; power via Cohen's h at &alpha; = 0.05. Python: pandas, SciPy, statsmodels, matplotlib.</p>
</body></html>"""
Path("report/report.html").write_text(html)
Path("index.html").write_text(html)  # GitHub Pages entry
print("report/report.html", len(html))
